// Post-analysis: decompile every function whose entry is in the boot block
// (0x0..0xFFFF) and write a combined C file + a function-list CSV.
// Output dir is passed as the first script arg.
import ghidra.app.script.GhidraScript;
import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import java.io.PrintWriter;
import java.io.File;

public class ExportBootDecomp extends GhidraScript {
    @Override
    public void run() throws Exception {
        String[] args = getScriptArgs();
        String outDir = (args.length > 0) ? args[0] : currentProgram.getExecutablePath();
        long BOOT_LO = 0x0L, BOOT_HI = 0x10000L;

        DecompInterface dec = new DecompInterface();
        dec.openProgram(currentProgram);

        File cFile = new File(outDir, "boot_decompiled.c");
        File csvFile = new File(outDir, "boot_functions.csv");
        PrintWriter c = new PrintWriter(cFile);
        PrintWriter csv = new PrintWriter(csvFile);
        csv.println("entry,name,size,calling_conv");

        c.println("/* Decompiled boot block 0x00000000-0x0000FFFF");
        c.println(" * Program: " + currentProgram.getName());
        c.println(" * Language: " + currentProgram.getLanguageID());
        c.println(" * Generated by Ghidra headless (RH850:LE:32:default) */\n");

        FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
        int n = 0, ok = 0;
        while (it.hasNext()) {
            Function f = it.next();
            long ep = f.getEntryPoint().getOffset();
            if (ep < BOOT_LO || ep >= BOOT_HI) continue;
            n++;
            csv.println(String.format("0x%05X,%s,%d,%s", ep, f.getName(),
                    f.getBody().getNumAddresses(), f.getCallingConventionName()));
            DecompileResults res = dec.decompileFunction(f, 60, monitor);
            c.println("/* ===== " + f.getName() + " @ 0x" + Long.toHexString(ep)
                    + " (size " + f.getBody().getNumAddresses() + ") ===== */");
            if (res != null && res.decompileCompleted() && res.getDecompiledFunction() != null) {
                c.println(res.getDecompiledFunction().getC());
                ok++;
            } else {
                c.println("/* decompile failed: "
                        + (res != null ? res.getErrorMessage() : "null") + " */");
            }
            c.println();
        }
        c.close(); csv.close();
        println("boot functions: " + n + " (decompiled OK: " + ok + ")");
        println("wrote: " + cFile.getAbsolutePath());
        println("wrote: " + csvFile.getAbsolutePath());
    }
}
